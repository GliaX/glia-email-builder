/**
 * Email Template form integration.
 *
 * Adds the block-builder entry point to ERPNext's standard Email Template
 * form without replacing it: the classic HTML editor remains available for
 * advanced users and for templates that pre-date the builder.
 */
frappe.ui.form.on("Email Template", {
	refresh(frm) {
		if (frm.is_new()) {
			if (frm.__gebNewButtonAdded) return;
			frm.__gebNewButtonAdded = true;
			frm.add_custom_button(
				__("Design with Blocks"),
				() => {
					frappe.msgprint({
						title: __("Open the Email Builder"),
						indicator: "blue",
						message:
							__(
								"Block designs are edited on their own page. Save this template first, or create a new email from the builder."
							) +
							'<div class="margin-top"><a class="btn btn-primary btn-sm" href="/desk/email-builder">' +
							__("Open the Email Builder") +
							"</a></div>",
					});
				},
				__("Actions")
			);
			return;
		}

		const openBuilder = () => {
			window.location.href = "/desk/email-builder?template=" + encodeURIComponent(frm.doc.name);
		};
		const openBuilderSaving = () => {
			if (!frm.is_dirty()) {
				openBuilder();
				return;
			}
			frm.save().then(openBuilder);
		};

		if (!frm.__gebBuilderButtonAdded) {
			frm.__gebBuilderButtonAdded = true;
			frm.add_custom_button(__("Design with Blocks"), openBuilderSaving, __("Actions"));
			frm.page.add_inner_button(__("Design with Blocks"), openBuilderSaving);
		}

		frappe
			.call({
				method: "glia_email_builder.api.get_template_status",
				args: { template: frm.doc.name },
			})
			.then((response) => {
				const status = response.message || {};
				if (status.has_design) {
					frm.dashboard.add_indicator(__("Block Builder design"), "blue");
					frm.set_df_property(
						"response_html",
						"description",
						__(
							"This HTML is generated by the Email Builder. Edit the content in the builder; changes made here will be overwritten the next time the design is saved."
						)
					);
					if (!status.can_write) {
						frm.dashboard.add_indicator(__("Read-only builder access"), "orange");
					}
				}
			})
			.catch(() => {});
	},
});
